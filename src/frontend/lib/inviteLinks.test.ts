import {makeInviteURL} from '@comapeo/core/invite-urls.js';
import {parseInviteLink, isInviteLinkExpired} from './inviteLinks';

const INVITE_ID = 'a'.repeat(64);
const SWARM_KEY = 'b'.repeat(64);
const EXPIRES_AT = 1790000000000;

function makeLink(
  overrides: Partial<Parameters<typeof makeInviteURL>[0]> = {},
) {
  return makeInviteURL({
    inviteIdString: INVITE_ID,
    swarmPublicKey: SWARM_KEY,
    invitorName: 'Jessica',
    projectName: 'Treeline East',
    expiresAt: EXPIRES_AT,
    ...overrides,
  });
}

describe('parseInviteLink', () => {
  it('round-trips a link generated by core', () => {
    expect(parseInviteLink(makeLink())).toEqual({
      inviteIdString: INVITE_ID,
      swarmPublicKey: SWARM_KEY,
      invitorName: 'Jessica',
      projectName: 'Treeline East',
      expiresAt: EXPIRES_AT,
    });
  });

  it.each([
    ['accents', 'José Ramírez', 'Proyecto Río Ñuble'],
    ['CJK', '中村', '森林プロジェクト'],
    ['emoji', 'Jessica', 'Ogiek 🌳'],
    ['reserved URL characters', 'A & B', 'North/South Ridge #4'],
  ])('preserves %s in names', (_label, invitorName, projectName) => {
    const invite = parseInviteLink(makeLink({invitorName, projectName}));
    expect(invite).toMatchObject({invitorName, projectName});
  });

  it.each([
    ['a non-invite https URL', 'https://a.comapeo.app/something#i=1'],
    ['the invite page with no hash', 'https://a.comapeo.app/invite'],
    ['an empty string', ''],
    ['unparseable text', 'not a url at all'],
  ])('returns null for %s', (_label, url) => {
    expect(parseInviteLink(url)).toBeNull();
  });

  it('returns null when a required param is missing', () => {
    const withoutProjectName = makeLink().replace(/&p=[^&]*/, '');
    expect(parseInviteLink(withoutProjectName)).toBeNull();
  });

  it('returns null when a key is the wrong length', () => {
    expect(
      parseInviteLink(makeLink().replace(/#i=[^&]*/, '#i=ABCDEF')),
    ).toBeNull();
  });

  it('returns null for a negative expiry that core lets through', () => {
    expect(parseInviteLink(makeLink().replace(/&e=[^&]*/, '&e=-5'))).toBeNull();
  });
});

describe('isInviteLinkExpired', () => {
  const invite = parseInviteLink(makeLink())!;

  it('is false before the expiry', () => {
    expect(isInviteLinkExpired(invite, EXPIRES_AT - 1)).toBe(false);
  });

  it('is true at and after the expiry', () => {
    expect(isInviteLinkExpired(invite, EXPIRES_AT)).toBe(true);
    expect(isInviteLinkExpired(invite, EXPIRES_AT + 1)).toBe(true);
  });
});
